def rc04(x):
    """Reactor network design."""
    c, n = columns(x), len(x)
    k1, k3 = 0.09755988, 0.0391908
    k2, k4 = 0.99 * k1, 0.9 * k3
    h = stack(
        n,
        c(1) + k1 * c(2) * c(5) - 1,
        c(2) - c(1) + k2 * c(2) * c(6),
        c(3) + c(1) + k3 * c(3) * c(5) - 1,
        c(4) - c(3) + c(2) - c(1) + k4 * c(4) * c(6),
    )
    return -c(4), stack(n, c(5) ** 0.5 + c(6) ** 0.5 - 4), h


def rc05(x):
    """Haverly's pooling problem."""
    c, n = columns(x), len(x)
    f = -(9 * c(1) + 15 * c(2) - 6 * c(3) - 16 * c(4) - 10 * (c(5) + c(6)))
    g = stack(n, c(9) * c(7) + 2 * c(5) - 2.5 * c(1), c(9) * c(8) + 2 * c(6) - 1.5 * c(2))
    h = stack(
        n,
        c(7) + c(8) - c(3) - c(4),
        c(1) - c(7) - c(5),
        c(2) - c(8) - c(6),
        c(9) * c(7) + c(9) * c(8) - 3 * c(3) - c(4),
    )
    return f, g, h


