def rc01(x):
    """Heat exchanger network design (case 1)."""
    c, n = columns(x), len(x)
    f = 35 * c(1) ** 0.6 + 35 * c(2) ** 0.6
    h = stack(
        n,
        200 * c(1) * c(4) - c(3),
        200 * c(2) * c(6) - c(5),
        c(3) - 10000 * (c(7) - 100),
        c(5) - 10000 * (300 - c(7)),
        c(3) - 10000 * (600 - c(8)),
        c(5) - 10000 * (900 - c(9)),
        c(4) * np.log(np.abs(c(8) - 100) + 1e-8) - c(4) * np.log((600 - c(7)) + 1e-8) - c(8) + c(7) + 500,
        c(6) * np.log(np.abs(c(9) - c(7)) + 1e-8) - c(6) * np.log(600) - c(9) + c(7) + 600,
    )
    return f, none(n), h


